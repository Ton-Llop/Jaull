"""Start, watch and stop the detached llama-server behind ``jaull serve``.

One server per user data directory. Its state (PID, process start time, address,
command line) is a JSON file next to its log, so ``serve status`` and
``serve stop`` work from a later shell. Before signalling a PID, the manager
checks that it is still the llama-server it started: same start time, and a
llama-server executable, so a reused PID is never killed.
"""

from __future__ import annotations

import os
import secrets
import shlex
import socket
import subprocess
import sys
import time
from collections.abc import Callable
from dataclasses import dataclass
from datetime import UTC, datetime
from pathlib import Path

import httpx
import psutil
from pydantic import BaseModel, ConfigDict, ValidationError

from jaull.runtime import policies

STATE_SCHEMA_VERSION = 1
_CREATE_TIME_TOLERANCE_SECONDS = 1.0
_HEALTH_REQUEST_TIMEOUT_SECONDS = 2.0
_PORT_SEARCH_RANGE = 100
_LOOPBACK = "127.0.0.1"
# Any routable address works: connecting a UDP socket sends nothing and only
# selects the interface the system would use (TEST-NET-1, RFC 5737).
_ROUTE_PROBE_ADDRESS = ("192.0.2.1", 9)

HealthCheck = Callable[[str], int | None]


class ServerProcessError(RuntimeError):
    """The server could not be started, or the saved state is not usable."""


class ServerState(BaseModel):
    model_config = ConfigDict(frozen=True)

    schema_version: int = STATE_SCHEMA_VERSION
    pid: int
    create_time: float
    host: str
    port: int
    tls: bool = False
    alias: str
    argv: list[str]
    log_path: str
    started_at: str

    @property
    def url(self) -> str:
        """Address to use from this PC (a LAN server listens on every interface)."""
        host = _LOOPBACK if self.host == policies.LLAMA_SERVER_LAN_HOST else self.host
        return _url(host, self.port, tls=self.tls)


@dataclass(frozen=True)
class ServerStatus:
    state: ServerState | None
    running: bool
    healthy: bool


class ServerProcessManager:
    def __init__(
        self,
        directory: Path,
        *,
        health_check: HealthCheck | None = None,
        sleep: Callable[[float], None] = time.sleep,
        clock: Callable[[], float] = time.monotonic,
    ) -> None:
        self.directory = directory
        self._health = health_check or _http_health
        self._sleep = sleep
        self._clock = clock

    @property
    def state_path(self) -> Path:
        return self.directory / "server.json"

    @property
    def log_path(self) -> Path:
        return self.directory / "server.log"

    @property
    def api_key_path(self) -> Path:
        return self.directory / "api-key"

    def ensure_api_key(self) -> tuple[Path, str | None]:
        """The API key file, and the key itself only when it was just created."""
        path = self.api_key_path
        if path.is_file() and path.read_text(encoding="utf-8").strip():
            return path, None
        self.directory.mkdir(parents=True, exist_ok=True)
        key = secrets.token_urlsafe(policies.LLAMA_SERVER_API_KEY_BYTES)
        descriptor = os.open(path, os.O_WRONLY | os.O_CREAT | os.O_TRUNC, 0o600)
        with os.fdopen(descriptor, "w", encoding="utf-8") as handle:
            handle.write(key + "\n")
        return path, key

    def write_start_script(self, argv: list[str], *, windows: bool) -> Path:
        """The same command as a script, to start the server by hand or at boot."""
        self.directory.mkdir(parents=True, exist_ok=True)
        if windows:
            path = self.directory / "start-server.bat"
            path.write_text(
                "@echo off\r\nREM Generated by Jaull (jaull serve start).\r\n"
                + subprocess.list2cmdline(argv) + "\r\n",
                encoding="utf-8",
                newline="",
            )
            return path
        path = self.directory / "start-server.sh"
        path.write_text(
            "#!/bin/sh\n# Generated by Jaull (jaull serve start).\nexec "
            + shlex.join(argv) + "\n",
            encoding="utf-8",
            newline="",
        )
        path.chmod(0o755)
        return path

    def start(
        self,
        argv: list[str],
        *,
        host: str,
        port: int,
        alias: str,
        tls: bool = False,
        health_timeout_seconds: float = policies.LLAMA_SERVER_HEALTH_TIMEOUT_SECONDS,
        poll_seconds: float = policies.LLAMA_SERVER_HEALTH_POLL_SECONDS,
    ) -> ServerState:
        current = self.status()
        if current.running and current.state is not None:
            raise ServerProcessError(
                f"A server is already running (pid {current.state.pid}, {current.state.url}). "
                "Stop it first with `jaull serve stop`."
            )
        if not port_available(host, port):
            suggestion = free_port(host, port + 1)
            hint = f" Port {suggestion} is free." if suggestion is not None else ""
            raise ServerProcessError(f"Port {port} is already in use.{hint}")

        self.directory.mkdir(parents=True, exist_ok=True)
        with self.log_path.open("ab") as log:
            process = subprocess.Popen(
                argv,
                stdin=subprocess.DEVNULL,
                stdout=log,
                stderr=subprocess.STDOUT,
                creationflags=_detached_creationflags(),
                # POSIX: a new session, so closing the terminal does not stop it.
                start_new_session=sys.platform != "win32",
            )
        state = ServerState(
            pid=process.pid,
            create_time=_create_time(process.pid),
            host=host,
            port=port,
            tls=tls,
            alias=alias,
            argv=argv,
            log_path=str(self.log_path),
            started_at=datetime.now(UTC).isoformat(timespec="seconds"),
        )
        self.state_path.write_text(state.model_dump_json(indent=2), encoding="utf-8")
        try:
            self._wait_healthy(process, state, health_timeout_seconds, poll_seconds)
        except ServerProcessError:
            self.state_path.unlink(missing_ok=True)
            raise
        return state

    def stop(self, *, timeout_seconds: float = policies.LLAMA_SERVER_STOP_TIMEOUT_SECONDS) -> bool:
        """Stop the saved server. ``False`` when there was none running."""
        state = self._load()
        if state is None:
            return False
        process = _verified_process(state)
        if process is None:
            self.state_path.unlink(missing_ok=True)
            return False
        process.terminate()
        try:
            process.wait(timeout=timeout_seconds)
        except psutil.TimeoutExpired:
            process.kill()
            process.wait(timeout=timeout_seconds)
        self.state_path.unlink(missing_ok=True)
        return True

    def status(self) -> ServerStatus:
        state = self._load()
        if state is None:
            return ServerStatus(state=None, running=False, healthy=False)
        if _verified_process(state) is None:
            return ServerStatus(state=state, running=False, healthy=False)
        healthy = self._health(_health_url(state)) == 200
        return ServerStatus(state=state, running=True, healthy=healthy)

    def log_tail(self, lines: int = policies.LLAMA_SERVER_LOG_TAIL_LINES) -> str:
        if not self.log_path.is_file():
            return ""
        text = self.log_path.read_text(encoding="utf-8", errors="replace")
        return "\n".join(text.splitlines()[-lines:])

    def _wait_healthy(
        self,
        process: subprocess.Popen[bytes],
        state: ServerState,
        timeout_seconds: float,
        poll_seconds: float,
    ) -> None:
        url = _health_url(state)
        deadline = self._clock() + timeout_seconds
        while True:
            code = process.poll()
            if code is not None:
                raise ServerProcessError(
                    f"llama-server exited with code {code} before it was ready. "
                    f"Last log lines:\n{self.log_tail()}"
                )
            if self._health(url) == 200:
                return
            if self._clock() >= deadline:
                _terminate(process)
                raise ServerProcessError(
                    f"llama-server did not become ready within {timeout_seconds:.0f} s and was "
                    f"stopped. Last log lines:\n{self.log_tail()}"
                )
            self._sleep(poll_seconds)

    def _load(self) -> ServerState | None:
        if not self.state_path.is_file():
            return None
        try:
            return ServerState.model_validate_json(self.state_path.read_text(encoding="utf-8"))
        except ValidationError as exc:
            raise ServerProcessError(
                f"Server state {self.state_path} is not readable ({exc.error_count()} errors). "
                "Check that no llama-server is running, then delete the file."
            ) from exc


def port_available(host: str, port: int) -> bool:
    """Nothing answers on ``port`` and it can be bound on ``host``."""
    with socket.socket(socket.AF_INET, socket.SOCK_STREAM) as probe:
        probe.settimeout(_HEALTH_REQUEST_TIMEOUT_SECONDS)
        if probe.connect_ex((_LOOPBACK, port)) == 0:
            return False
    with socket.socket(socket.AF_INET, socket.SOCK_STREAM) as server:
        if sys.platform != "win32":
            # Ignore sockets in TIME_WAIT; on Windows this option would allow
            # binding a port another process is using.
            server.setsockopt(socket.SOL_SOCKET, socket.SO_REUSEADDR, 1)
        try:
            server.bind((host, port))
        except OSError:
            return False
    return True


def free_port(host: str, start: int) -> int | None:
    for port in range(start, start + _PORT_SEARCH_RANGE):
        if port_available(host, port):
            return port
    return None


def lan_ipv4() -> tuple[str, str] | None:
    """(address, netmask) of the interface used for outgoing traffic, if any."""
    with socket.socket(socket.AF_INET, socket.SOCK_DGRAM) as probe:
        try:
            probe.connect(_ROUTE_PROBE_ADDRESS)
        except OSError:
            return None
        address = str(probe.getsockname()[0])
    for addresses in psutil.net_if_addrs().values():
        for entry in addresses:
            if entry.family == socket.AF_INET and entry.address == address and entry.netmask:
                return address, entry.netmask
    return None


def _url(host: str, port: int, *, tls: bool) -> str:
    return f"{'https' if tls else 'http'}://{host}:{port}"


def _health_url(state: ServerState) -> str:
    return state.url + "/health"


def _http_health(url: str) -> int | None:
    # Local probe of our own server; a self-signed certificate is expected with TLS.
    try:
        response = httpx.get(url, timeout=_HEALTH_REQUEST_TIMEOUT_SECONDS, verify=False)
    except httpx.HTTPError:
        return None
    return response.status_code


def _detached_creationflags() -> int:
    """Windows: no console and its own process group, so it outlives the shell."""
    if sys.platform != "win32":
        return 0
    return int(getattr(subprocess, "DETACHED_PROCESS", 0)) | int(
        getattr(subprocess, "CREATE_NEW_PROCESS_GROUP", 0)
    )


def _create_time(pid: int) -> float:
    try:
        return psutil.Process(pid).create_time()
    except psutil.Error:
        return 0.0


def _verified_process(state: ServerState) -> psutil.Process | None:
    try:
        process = psutil.Process(state.pid)
        if abs(process.create_time() - state.create_time) > _CREATE_TIME_TOLERANCE_SECONDS:
            return None
        if process.status() == psutil.STATUS_ZOMBIE:
            return None
        names = [process.name(), *process.cmdline()[:2]]
    except psutil.Error:
        return None
    if not any(Path(name).name.casefold().startswith("llama-server") for name in names):
        return None
    return process


def _terminate(process: subprocess.Popen[bytes]) -> None:
    process.terminate()
    try:
        process.wait(timeout=policies.LLAMA_SERVER_STOP_TIMEOUT_SECONDS)
    except subprocess.TimeoutExpired:
        process.kill()
        process.wait()


